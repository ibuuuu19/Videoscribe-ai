def _e(x) -> str:
    return _h.escape(str(x if x is not None else ""), quote=True)


def _sentences(text: str):
    text = re.sub(r"\s+", " ", str(text or "")).strip()
    parts = re.split(r"(?<=[.!?…])\s+(?=[A-ZÀ-ÖØ-Ý«\"“0-9])", text)
    return [p.strip() for p in parts if p.strip()]


def _cut(s: str, n: int) -> str:
    s = s.strip()
    if len(s) <= n:
        return s
    cut = s[:n].rsplit(" ", 1)[0].rstrip(",;:.- ")
    return cut + "…"


def _headline(note: str):
    """(titre court, reste du texte) : « Intro : blabla » → ('Intro', 'blabla'), sinon première phrase."""
    note = re.sub(r"\s+", " ", str(note or "")).strip()
    m = re.match(r"^([^:.!?]{3,60}?)\s*:\s+(.+)$", note)
    if m:
        return m.group(1).strip(), m.group(2).strip()
    sents = _sentences(note)
    if not sents:
        return "", ""
    first = sents[0]
    if len(first) <= 90:
        return first.rstrip(".") if len(sents) > 1 else _cut(first, 90), " ".join(sents[1:])
    return _cut(first, 80), note


def _shade(hexcol: str, f: float) -> str:
    try:
        h = hexcol.lstrip("#")
        r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
        return "#%02X%02X%02X" % tuple(max(0, min(255, int(c * f))) for c in (r, g, b))
    except Exception:
        return hexcol


def export_presentation(data: dict, accent: str = "#2E6DB4", theme: str = "dark") -> str:
    d = data or {}
    L = _L.get(str(d.get("lang", "fr"))[:2], _L["fr"])
    notes = [n for n in (d.get("notes") or []) if str(n).strip()]
    kws = []
    for k in d.get("keywords") or []:
        try:
            kws.append((str(k[0]), int(k[1])) if isinstance(k, (list, tuple)) and len(k) > 1 else (str(k), 1))
        except Exception:
            kws.append((str(k), 1))
    qs = [q for q in (d.get("questions") or []) if str(q).strip()]
    title = d.get("title") or f"Résumé — {d.get('video_id', '')}"
    title = re.sub(r"^Résumé\s*[-–—]\s*", "", title) if len(title) > 40 else title
    vid = d.get("video_id", "")
    url = d.get("url") or (f"https://www.youtube.com/watch?v={vid}" if vid else "")
    date = d.get("date") or datetime.now().strftime("%d/%m/%Y %H:%M")
    words = d.get("total_words") or d.get("words") or sum(len(str(n).split()) for n in notes)
    acc, acc2 = accent, _shade(accent, 0.55)

    slides = []   # (titre pour la vue d'ensemble, html)

    def add(name, cls, inner):
        slides.append((name, f'<section class="slide {cls}">{inner}</section>'))

    # 1. Titre
    chips = f'<span class="chip">{_e(date)}</span><span class="chip">{_e(str(d.get("lang", "fr")).upper())}</span>'
    if words:
        chips += f'<span class="chip">{int(words):,} {L["words"]}</span>'.replace(",", " ")
    chips += f'<span class="chip">{len(notes)} {L["sections"]}</span>'
    add(title, "s-title", f'''<div class="orb o1"></div><div class="orb o2"></div><div class="grid"></div>
      <div class="brand"><i class="logo"></i><b>VideoScribe</b> AI</div>
      <div class="center"><div class="kicker a1">Studio · VideoScribe AI</div>
      <h1 class="a2">{_e(title)}</h1><div class="chips a3">{chips}</div></div>
      <div class="foot-l a4">{_e(url)}</div>''')

    # 2. Sommaire
    heads = [(_headline(n)[0] or _cut(n, 60)) for n in notes]
    if heads:
        rows = "".join(f'<li class="a{min(i + 1, 9)}"><span class="n">{i + 1:02d}</span><span class="t">{_e(_cut(hd, 70))}</span></li>' for i, hd in enumerate(heads[:9]))
        more = f'<div class="more a9">+ {len(heads) - 9}</div>' if len(heads) > 9 else ""
        add(L["agenda"], "s-agenda", f'<div class="bar"></div><h2>{_e(L["agenda"])}</h2><ol class="agenda{" two" if len(heads) > 5 else ""}">{rows}</ol>{more}')

    # 3. Chiffres clés
    stats = [(f"{int(words):,}".replace(",", " "), L["words"]), (str(len(notes)), L["sections"]),
             (str(d.get("num_chunks") or len(notes)), L["chunks"])]
    pt = d.get("processing_time")
    if pt:
        stats.append((f"{float(pt):.0f} s", L["time"]))
    cards = "".join(f'<div class="stat a{i + 1}"><b data-count="{_e(v)}">{_e(v)}</b><span>{_e(lbl)}</span></div>' for i, (v, lbl) in enumerate(stats))
    add(L["figures"], "s-stats", f'<div class="bar"></div><h2>{_e(L["figures"])}</h2><div class="stats n{len(stats)}">{cards}</div>')

    # 4. Une diapositive par section
    shown = notes[:11]
    kw_sorted = [k for k, _ in sorted(kws, key=lambda x: -x[1])]
    for i, note in enumerate(shown):
        head, rest = _headline(note)
        if head.endswith("…") or (len(head) > 70):
            # première phrase trop longue pour un titre : on prend le concept clé le plus présent dans la section
            low = note.lower()
            found = next((k for k in kw_sorted if k.lower() in low), None)
            head = (found[:1].upper() + found[1:]) if found else f'{L["section"]} {i + 1}'
            rest = note
        bullets = _sentences(rest)[:4] if rest else []
        if len(bullets) == 1 and len(bullets[0]) > 260:
            bullets = [_cut(bullets[0], 420)]
        lis = "".join(f'<li class="a{min(j + 2, 9)}">{_e(b)}</li>' for j, b in enumerate(bullets))
        body = f'<ul class="bul fit">{lis}</ul>' if len(bullets) > 1 else f'<p class="lead fit a2">{_e(bullets[0] if bullets else "")}</p>'
        layout = "left" if i % 2 == 0 else "right"
        add(head or f'{L["section"]} {i + 1}', f"s-sec {layout}", f'''<div class="side"><div class="big a1">{i + 1:02d}</div><div class="lab">{_e(L["section"])} {i + 1} / {len(notes)}</div></div>
        <div class="main"><h2 class="a1">{_e(head)}</h2>{body}</div>''')
    if len(notes) > len(shown):
        rest_items = "".join(f'<li class="a{min(j + 2, 9)}">{_e(_cut(_headline(n)[0] or n, 110))}</li>' for j, n in enumerate(notes[len(shown):][:8]))
        add("+", "s-sec left", f'<div class="side"><div class="big a1">+{len(notes) - len(shown)}</div></div><div class="main"><h2 class="a1">{_e(L["section"])}s</h2><ul class="bul fit">{rest_items}</ul></div>')

    # 5. Concepts clés (barres horizontales)
    if kws:
        top = sorted(kws, key=lambda x: -x[1])[:8]
        mx = max(c for _, c in top) or 1
        bars = "".join(f'<div class="kw a{min(i + 1, 9)}"><span class="k">{_e(k)}</span><span class="track"><i style="width:{max(8, int(100 * c / mx))}%"></i></span><span class="c">{c}</span></div>' for i, (k, c) in enumerate(top))
        add(L["concepts"], "s-kw", f'<div class="bar"></div><h2>{_e(L["concepts"])}</h2><div class="kws">{bars}</div>')

    # 6. Questions
    if qs:
        qs = qs[:8]
        per = -(-len(qs) // -(-len(qs) // 4))   # répartition équilibrée (5 → 3 + 2)
        for part in range(0, len(qs), per):
            chunk = qs[part:part + per]
            cards = "".join(f'<div class="q a{min(i + 1, 9)}"><span class="qn">{part + i + 1}</span><p>{_e(_cut(q, 150))}</p></div>' for i, q in enumerate(chunk))
            add(L["questions"], "s-q", f'<div class="bar"></div><h2>{_e(L["questions"])}</h2><div class="qs">{cards}</div>')

    # 7. À retenir
    take = [(_headline(n)[0] or _cut(n, 100)) for n in notes[:4]]
    if take:
        items = "".join(f'<li class="a{i + 1}"><span class="ck">✓</span><span>{_e(_cut(t, 120))}</span></li>' for i, t in enumerate(take))
        add(L["takeaways"], "s-take", f'<div class="bar"></div><h2>{_e(L["takeaways"])}</h2><ul class="take">{items}</ul>')

    # 8. Clôture
    add(L["thanks"], "s-end", f'''<div class="orb o1"></div><div class="orb o2"></div><div class="grid"></div>
      <div class="center"><h1 class="a1">{_e(L["thanks"])}</h1><div class="sub a2">{_e(title)}</div>
      {f'<div class="src a3">{_e(L["source"])} · {_e(url)}</div>' if url else ''}</div>
      <div class="brand"><i class="logo"></i><b>VideoScribe</b> AI</div>''')

    total = len(slides)
    parts = []
    for i, (_, h) in enumerate(slides):
        h = h.replace("<section", '<section data-i="%d"' % i, 1)
        if "s-title" not in h[:60] and "s-end" not in h[:60]:
            h = h[:-len("</section>")] + '<div class="ftr"><span>%s</span><span>%d / %d</span></div></section>' % (_e(_cut(title, 60)), i + 1, len(slides))
        parts.append(h)
    deck = "".join(parts)
    ov = "".join(f'<button class="ovc" data-go="{i}"><em>{i + 1:02d}</em><span>{_e(_cut(nm, 60))}</span></button>' for i, (nm, _) in enumerate(slides))

    return (_TPL.replace("@@LANG@@", str(d.get("lang", "fr"))[:2]).replace("@@TITLE@@", _e(title))
            .replace("@@ACC@@", acc).replace("@@ACC2@@", acc2).replace("@@THEME@@", "light" if theme == "light" else "dark")
            .replace("@@DECK@@", deck).replace("@@OVERVIEW@@", ov).replace("@@TOTAL@@", str(total))
            .replace("@@HINT@@", _e(L["hint"])).replace("@@OVL@@", _e(L["overview"])).replace("@@PRINT@@", _e(L["print"]))
            .replace("@@FULL@@", _e(L["full"])).replace("@@THEMEL@@", _e(L["theme"])).replace("@@FOOT@@", _e(title)[:60]))


